"""
Stage 4 Kaggle Automation: Programmatic Remote GPU Runner
Automates Wan 2.2 Image-to-Video generation using Kaggle API.

Features:
- Bundles current 9 FLUX keyframes directly into a self-extracting notebook
- Pushes kernel to Kaggle via authenticated Kaggle API (enable_gpu=True, enable_internet=True)
- Monitors remote GPU job status (queued -> running -> complete)
- Downloads generated MP4 video clips into outputs/wan_drops/ for automatic pipeline ingestion
"""

import os
import sys
import time
import json
import base64
import shutil
import zipfile
from pathlib import Path

# Ensure pipeline root is in sys.path
PIPELINE_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = PIPELINE_DIR.parent
sys.path.insert(0, str(PIPELINE_DIR))
sys.path.insert(0, str(Path.home() / "Library/Python/3.9/lib/python/site-packages"))

from common import PROJECT_ROOT, OUTPUTS_DIR, load_storyboard, log_run

KEYFRAMES_DIR = OUTPUTS_DIR / "keyframes"
WAN_DROPS_DIR = OUTPUTS_DIR / "wan_drops"
NOTEBOOKS_DIR = PROJECT_ROOT / "notebooks"
JOB_DIR = NOTEBOOKS_DIR / "kaggle_job"

KERNEL_SLUG = "heritage-short-wan2"


def ensure_kaggle_authenticated():
    """Ensure ~/.kaggle/kaggle.json exists and return authenticated KaggleApi instance."""
    from common import load_storyboard
    import os

    env_path = PROJECT_ROOT / ".env"
    username = os.environ.get("KAGGLE_USERNAME")
    key = os.environ.get("KAGGLE_KEY")

    if not username or not key:
        if env_path.exists():
            for line in env_path.read_text().splitlines():
                if "=" in line and not line.strip().startswith("#"):
                    k, v = line.split("=", 1)
                    if k.strip() == "KAGGLE_USERNAME":
                        username = v.strip()
                    elif k.strip() == "KAGGLE_KEY":
                        key = v.strip()

    if not username or not key:
        raise ValueError("Missing KAGGLE_USERNAME or KAGGLE_KEY in environment or .env file.")

    kaggle_dir = Path.home() / ".kaggle"
    kaggle_dir.mkdir(parents=True, exist_ok=True)
    kaggle_json = kaggle_dir / "kaggle.json"
    kaggle_json.write_text(json.dumps({"username": username, "key": key}))
    kaggle_json.chmod(0o600)

    os.environ["KAGGLE_USERNAME"] = username
    os.environ["KAGGLE_KEY"] = key

    import kaggle
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()
    return api, username


def prepare_bundle_notebook():
    """
    Creates a self-extracting notebook inside notebooks/kaggle_job/ containing:
    1. Base64 payload of all 9 current FLUX keyframes (unpacks instantly on Kaggle)
    2. Diffusers WanImageToVideoPipeline batch generator
    3. Packaging cell creating wan_drops.zip
    """
    JOB_DIR.mkdir(parents=True, exist_ok=True)

    # Pack 9 keyframes into an in-memory zip
    zip_bytes_io = bytearray()
    zip_path = JOB_DIR / "temp_keyframes.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for i in range(1, 10):
            k_file = KEYFRAMES_DIR / f"shot_0{i}.png"
            if k_file.exists():
                zf.write(k_file, arcname=f"shot_0{i}.png")
    
    b64_zip = base64.b64encode(zip_path.read_bytes()).decode("utf-8")
    zip_path.unlink()

    # Load source notebook
    src_nb_path = NOTEBOOKS_DIR / "wan2_kaggle_pipeline.ipynb"
    with open(src_nb_path, "r") as f:
        nb = json.load(f)

    # Insert self-extraction cell at beginning
    extract_cell = {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": [
            "# 0. Self-Extracting Keyframe Bundle (Auto-generated by Antigravity Pipeline)\n",
            "import base64, io, zipfile, os\n",
            f'B64_DATA = "{b64_zip}"\n',
            'with zipfile.ZipFile(io.BytesIO(base64.b64decode(B64_DATA))) as zf:\n',
            '    zf.extractall(".")\n',
            'print("✅ All 9 FLUX keyframes extracted successfully into Kaggle workspace!")\n',
            '!ls -lh shot_0*.png\n'
        ]
    }

    # Ensure cell 0 is the extractor
    nb["cells"] = [nb["cells"][0], extract_cell] + nb["cells"][1:]

    out_nb = JOB_DIR / "wan2_kaggle_pipeline.ipynb"
    with open(out_nb, "w") as f:
        json.dump(nb, f, indent=2)

    return out_nb


def push_kaggle_job():
    """Push kernel to Kaggle and trigger GPU execution."""
    print("🚀 [Kaggle Automation] Preparing self-extracting notebook bundle...")
    api, username = ensure_kaggle_authenticated()
    kernel_id = f"{username}/{KERNEL_SLUG}"

    prepare_bundle_notebook()

    # Create kernel-metadata.json
    metadata = {
        "id": kernel_id,
        "title": "The Heritage Short - Wan 2.2 Video Generator",
        "code_file": "wan2_kaggle_pipeline.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "machine_shape": "NvidiaTeslaT4"
    }

    metadata_path = JOB_DIR / "kernel-metadata.json"
    with open(metadata_path, "w") as f:
        json.dump(metadata, f, indent=2)

    print(f"📦 [Kaggle Automation] Pushing GPU kernel to Kaggle: {kernel_id}...")
    res = api.kernels_push(str(JOB_DIR))
    print(f"✅ [Kaggle Automation] Push successful: {res}")
    print(f"🔗 View on Kaggle: https://www.kaggle.com/code/{kernel_id}")
    return kernel_id


def check_kaggle_status():
    """Check status of remote Kaggle GPU job."""
    api, username = ensure_kaggle_authenticated()
    kernel_id = f"{username}/{KERNEL_SLUG}"
    status_dict = api.kernels_status(kernel_id)
    status = status_dict.get("status", "unknown")
    print(f"📊 [Kaggle Status] Kernel {kernel_id}: {status.upper()}")
    return status


def pull_kaggle_outputs():
    """Download generated MP4 video files into outputs/wan_drops/."""
    print("📥 [Kaggle Automation] Checking and downloading generated video outputs...")
    api, username = ensure_kaggle_authenticated()
    kernel_id = f"{username}/{KERNEL_SLUG}"
    WAN_DROPS_DIR.mkdir(parents=True, exist_ok=True)

    dest_dir = PROJECT_ROOT / "outputs" / "kaggle_downloads"
    dest_dir.mkdir(parents=True, exist_ok=True)

    api.kernels_output(kernel_id, path=str(dest_dir))
    print(f"✅ Downloaded kernel outputs to {dest_dir}")

    # Inspect downloaded files and extract wan_drops
    extracted = 0
    for p in dest_dir.glob("*.zip"):
        print(f"  📦 Unzipping {p.name}...")
        with zipfile.ZipFile(p, "r") as zf:
            zf.extractall(WAN_DROPS_DIR)
            extracted += len(zf.namelist())

    for mp4 in dest_dir.glob("*.mp4"):
        shutil.copy2(mp4, WAN_DROPS_DIR / mp4.name)
        extracted += 1

    print(f"🎉 Ingested {extracted} files into {WAN_DROPS_DIR}/")
    return extracted


def monitor_and_pull(interval_seconds=30, timeout_minutes=45):
    """Wait for Kaggle job to complete, then pull outputs and trigger pipeline reassembly."""
    api, username = ensure_kaggle_authenticated()
    kernel_id = f"{username}/{KERNEL_SLUG}"
    start_time = time.time()
    max_seconds = timeout_minutes * 60

    print(f"⏳ Monitoring Kaggle job {kernel_id} (polling every {interval_seconds}s)...")
    while time.time() - start_time < max_seconds:
        status_dict = api.kernels_status(kernel_id)
        status = status_dict.get("status", "unknown")
        elapsed = int(time.time() - start_time)
        print(f"  [{elapsed}s elapsed] Status: {status}")

        if status == "complete":
            print("🎉 Kaggle remote GPU run complete!")
            pull_kaggle_outputs()
            print("🎬 Reassembling final films with Wan 2.2 clips...")
            from stage4_shots import run_shots_stage
            from stage6_assemble import run_assemble_stage
            run_shots_stage(force_regenerate=True)
            run_assemble_stage(radio_cut_only=False)
            print("✨ Final films reassembled with genuine Wan 2.2 shots!")
            return True
        elif status in ["error", "cancelAck", "cancelled"]:
            print(f"⚠️ Kaggle job ended with status: {status}")
            return False

        time.sleep(interval_seconds)

    print("⚠️ Timed out waiting for Kaggle job.")
    return False


if __name__ == "__main__":
    action = sys.argv[1] if len(sys.argv) > 1 else "push"
    if action == "push":
        push_kaggle_job()
    elif action == "status":
        check_kaggle_status()
    elif action == "pull":
        pull_kaggle_outputs()
    elif action == "monitor":
        monitor_and_pull()
